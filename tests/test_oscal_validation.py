"""NIST OSCAL Schema Validation Test Suite.

This module validates that the JSON catalogs generated by our framework strictly
conform to the official NIST OSCAL Control Catalog JSON Schema (v1.1.1).
Validating against the official schema is essential for academic research credibility
and interoperability with enterprise GRC engines.
"""

from pathlib import Path
from typing import Any, Dict
import json
import pytest
import jsonschema  # type: ignore[import-untyped]

# Enable Unicode regex character classes (\p{L}, \p{N}) defined in NIST OSCAL schemas
try:
    import regex  # type: ignore[import-untyped]
    import jsonschema._keywords  # type: ignore[import-untyped]
    import jsonschema._format  # type: ignore[import-untyped]

    jsonschema._keywords.re = regex
    jsonschema._format.re = regex
except ImportError:
    pass

from src.main import run_pipeline


@pytest.fixture(scope="module")
def generated_catalogs_dir(
    tmp_path_factory: pytest.TempPathFactory, sample_data_path: Path
) -> Path:
    """Generates fresh OSCAL catalogs in a temporary directory for schema validation."""
    out_dir = tmp_path_factory.mktemp("schema_validation_catalogs")
    exit_code = run_pipeline(
        input_file=sample_data_path,
        output_dir=out_dir,
        regulation_filter=None,
        verbose=False,
    )
    assert exit_code == 0, "Pipeline must run successfully to produce catalogs for validation."
    return out_dir


@pytest.mark.parametrize(
    "catalog_filename",
    [
        "gdpr_catalog.json",
        "dora_catalog.json",
        "nis2_catalog.json",
        "unified_catalog.json",
    ],
)
def test_generated_catalogs_comply_with_nist_schema(
    generated_catalogs_dir: Path,
    oscal_schema_path: Path,
    catalog_filename: str,
) -> None:
    """WHAT: Validates each generated OSCAL catalog against NIST oscal_catalog_schema.json.

    WHY IT MATTERS:
    Ensures that catalogs across all supported regulatory regimes (GDPR, DORA, NIS2, and unified)
    strictly conform to NIST specifications without missing fields or invalid property types.
    """
    if not oscal_schema_path.exists():
        pytest.skip("NIST OSCAL schema not found. Download via curl command in README.")

    catalog_path = generated_catalogs_dir / catalog_filename
    assert catalog_path.exists(), f"Catalog {catalog_filename} was not generated."

    with open(catalog_path, "r", encoding="utf-8") as f:
        catalog_instance: Dict[str, Any] = json.load(f)

    with open(oscal_schema_path, "r", encoding="utf-8") as f:
        schema: Dict[str, Any] = json.load(f)

    # Validate catalog against NIST draft-07 JSON schema
    try:
        jsonschema.validate(instance=catalog_instance, schema=schema)
    except jsonschema.ValidationError as err:
        pytest.fail(
            f"Catalog {catalog_filename} failed NIST OSCAL schema validation: {err.message}"
        )
